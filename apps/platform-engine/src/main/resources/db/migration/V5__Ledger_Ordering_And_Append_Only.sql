-- Deterministic chain order: created_at is the transaction start time and can tie or invert.
ALTER TABLE ledger_events ADD COLUMN IF NOT EXISTS seq BIGINT GENERATED BY DEFAULT AS IDENTITY;

UPDATE ledger_events l
SET seq = ordered.rn
FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM ledger_events) ordered
WHERE l.id = ordered.id;

CREATE UNIQUE INDEX IF NOT EXISTS idx_ledger_seq ON ledger_events(seq);

-- The ledger is append-only; reject updates, deletes and truncation at the database level.
CREATE OR REPLACE FUNCTION ledger_events_reject_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'ledger_events is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ledger_events_no_update_delete
    BEFORE UPDATE OR DELETE ON ledger_events
    FOR EACH ROW EXECUTE FUNCTION ledger_events_reject_mutation();

CREATE TRIGGER ledger_events_no_truncate
    BEFORE TRUNCATE ON ledger_events
    FOR EACH STATEMENT EXECUTE FUNCTION ledger_events_reject_mutation();
